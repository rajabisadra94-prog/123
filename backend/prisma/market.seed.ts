export async function seedMarket(prisma: PrismaClient) {
  let cityCount = 0;
  for (const [governorate, cities] of IRAQ_GEO) {
    for (let i = 0; i < cities.length; i++) {
      const [name, nameAr] = cities[i];
      await prisma.marketCity.upsert({
        where: { governorate_name: { governorate, name } },
        update: {},
        create: { governorate, name, nameAr, sortOrder: i },
      });
      cityCount++;
    }
  }

  for (const p of PRODUCTS) {
    await prisma.marketProduct.upsert({ where: { name: p.name }, update: {}, create: p });
  }

  // قالب‌ها کلید یکتا ندارند، پس فقط اگر هیچ قالبی نبود ساخته می‌شوند
  if ((await prisma.marketTemplate.count()) === 0) {
    for (const t of TEMPLATES) {
      await prisma.marketTemplate.create({ data: { ...t, language: 'AR', channel: 'WHATSAPP' } });
    }
  }

  // نرخ تبدیل دلار به دینار عراق — برای نمایش معادل IQD کنار قیمت‌های دلاری
  await prisma.systemSetting.upsert({
    where: { key: 'IQD_PER_USD' },
    update: {},
    create: { key: 'IQD_PER_USD', value: '1320' },
  });

  console.log(`Market seed: ${IRAQ_GEO.length} استان، ${cityCount} شهر، ${PRODUCTS.length} محصول`);
}
